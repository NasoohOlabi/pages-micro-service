import json
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

SOURCE = 'https://tanzil.net/res/text/metadata/quran-data.xml'
root = ET.fromstring(urllib.request.urlopen(SOURCE).read())
surahs = root.find('suras').findall('sura')
pages = root.find('pages').findall('page')
assert len(surahs) == 114 and len(pages) == 604

page_starts = [
    int(surahs[int(page.attrib['sura']) - 1].attrib['start']) + int(page.attrib['aya']) - 1
    for page in pages
]
total_verses = sum(int(surah.attrib['ayas']) for surah in surahs)
page_ends = page_starts[1:] + [total_verses]
mapping = []
for surah in surahs:
    start = int(surah.attrib['start'])
    end = start + int(surah.attrib['ayas'])
    matching = [
        index + 1 for index, (page_start, page_end) in enumerate(zip(page_starts, page_ends))
        if start < page_end and end > page_start
    ]
    mapping.append({
        'name': surah.attrib['name'],
        'firstPage': min(matching),
        'lastPage': max(matching),
    })

assert [surah['name'] for surah in mapping if surah['lastPage'] == 604] == ['الإخلاص', 'الفلق', 'الناس']
output = Path(__file__).resolve().parents[1] / 'src/stats/surahPages.ts'
lines = [
    '// Generated by scripts/update-surah-pages.py from Tanzil Madani mushaf metadata.',
    '// Metadata (C) 2008-2009 Tanzil.info, CC BY: ' + SOURCE,
    'export const surahPages = [',
    *['  ' + json.dumps(surah, ensure_ascii=False).replace('"', "'") + ',' for surah in mapping],
    ']',
    '',
]
output.write_text('\n'.join(lines), encoding='utf-8')
print('Generated 114 surah boundaries covering 604 pages')
